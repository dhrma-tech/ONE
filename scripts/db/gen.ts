// Generates supabase/migrations/0001_init.sql and the tables part of docs/SCHEMA.md from apps/web/src/data/schema.ts.
// Run: pnpm db:gen
import { writeFileSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { TABLES, TABLE_NAMES, type Col, type TableDef, type TableName } from "../../apps/web/src/data/schema";
import { topoOrder } from "../../apps/web/src/data/order";

const root = join(import.meta.dirname, "..", "..");
const SQLT: Record<Col["t"], string> = {
  text: "text", int: "integer", num: "numeric", bool: "boolean", date: "date", ts: "timestamptz", time: "time",
  uuid: "uuid", jsonb: "jsonb", "text[]": "text[]", "int[]": "integer[]",
};

const lines: string[] = [];
const out = (s = "") => lines.push(s);
out("-- ONE schema. GENERATED by scripts/db/gen.ts from apps/web/src/data/schema.ts. Do not edit by hand.");
out("-- Every table: id, user_id (RLS owner), created_at, updated_at (client clock, last-write-wins),");
out("-- synced_at (server clock, used for incremental pulls), deleted_at (soft delete).");
out();
out();
out(`create or replace function public.one_touch() returns trigger language plpgsql as $$
begin
  if tg_op = 'UPDATE' and new.updated_at < old.updated_at then
    return old; -- last-write-wins: ignore stale writes
  end if;
  new.synced_at := now();
  if new.updated_at is null then new.updated_at := now(); end if;
  return new;
end $$;`);
out();

for (const t of topoOrder()) {
  const d = TABLES[t] as TableDef;
  out(`-- ${t}: ${d.doc}`);
  out(`create table if not exists public.${t} (`);
  const cols = [
    "  id uuid primary key default gen_random_uuid()",
    "  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade",
  ];
  for (const [name, c] of Object.entries(d.cols) as [string, Col][]) {
    let s = `  ${name} ${SQLT[c.t]}`;
    if (c.req) s += " not null";
    if (c.def) s += ` default ${c.def}`;
    if (c.ref) s += ` references public.${c.ref}(id) on delete cascade`;
    if (c.check) s += ` check (${c.check})`;
    cols.push(s);
  }
  cols.push(
    "  created_at timestamptz not null default now()",
    "  updated_at timestamptz not null default now()",
    "  synced_at timestamptz not null default now()",
    "  deleted_at timestamptz",
  );
  out(cols.join(",\n"));
  out(");");
  out(`create index if not exists ${t}_user_synced on public.${t} (user_id, synced_at);`);
  for (const i of d.idx ?? []) out(`create index if not exists ${t}_${i} on public.${t} (user_id, ${i});`);
  (d.unique ?? []).forEach((u, n) =>
    out(`create unique index if not exists ${t}_uq${n} on public.${t} (user_id, ${u.join(", ")})${d.serverOnly ? "" : " where deleted_at is null"};`),
  );
  out(`drop trigger if exists ${t}_touch on public.${t};`);
  out(`create trigger ${t}_touch before insert or update on public.${t} for each row execute function public.one_touch();`);
  out(`alter table public.${t} enable row level security;`);
  if (d.serverOnly) {
    out(`-- server only: RLS enabled with no policies, so only the service role can read/write.`);
    out(`revoke all on public.${t} from anon, authenticated;`);
  } else {
    out(`drop policy if exists "${t}_owner" on public.${t};`);
    out(`create policy "${t}_owner" on public.${t} for all to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));`);
    out(`revoke all on public.${t} from anon;`);
  }
  out(`comment on table public.${t} is '${d.doc.replace(/'/g, "''")}';`);
  for (const [name, c] of Object.entries(d.cols) as [string, Col][])
    if (c.doc) out(`comment on column public.${t}.${name} is '${c.doc.replace(/'/g, "''")}';`);
  out();
}
writeFileSync(join(root, "supabase", "migrations", "0001_init.sql"), lines.join("\n"));

// SCHEMA.md tables section
const md: string[] = [];
const groups = ["core", "library", "career", "college", "mind", "body", "persona", "server"] as const;
for (const g of groups) {
  md.push(`### ${g[0].toUpperCase()}${g.slice(1)}`);
  for (const t of TABLE_NAMES.filter((x) => (TABLES[x] as TableDef).group === g) as TableName[]) {
    const d = TABLES[t] as TableDef;
    md.push("", `#### \`${t}\`${d.private ? " (private)" : ""}${d.serverOnly ? " (server only)" : ""}`, d.doc, "");
    md.push("| Column | Type | Notes |", "|---|---|---|");
    for (const [name, c] of Object.entries(d.cols) as [string, Col][]) {
      const notes = [c.req ? "required" : "", c.def ? `default \`${c.def}\`` : "", c.ref ? `→ \`${c.ref}.id\`` : "", c.doc ?? ""].filter(Boolean).join("; ");
      md.push(`| \`${name}\` | ${SQLT[c.t]} | ${notes.replace(/\|/g, "/")} |`);
    }
    if (d.unique?.length) md.push("", `Unique per user: ${d.unique.map((u) => `(${u.join(", ")})`).join(", ")}.`);
  }
  md.push("");
}
const schemaPath = join(root, "docs", "SCHEMA.md");
const cur = readFileSync(schemaPath, "utf8");
const START = "<!-- TABLES:START -->";
const END = "<!-- TABLES:END -->";
const body = `${START}\n${md.join("\n")}\n${END}`;
writeFileSync(schemaPath, cur.includes(START) ? cur.replace(new RegExp(`${START}[\s\S]*${END}`), body) : `${cur}\n${body}\n`);
console.log(`generated ${TABLE_NAMES.length} tables`);

// TypeScript row types for the client
const TST: Record<Col["t"], string> = {
  text: "string", int: "number", num: "number", bool: "boolean", date: "string", ts: "string", time: "string",
  uuid: "string", jsonb: "any", "text[]": "string[]", "int[]": "number[]",
};
const pascal = (s: string) => s.replace(/(^|_)([a-z])/g, (_, __, c: string) => c.toUpperCase());
const ts: string[] = [
  "// GENERATED by scripts/db/gen.ts from schema.ts. Do not edit by hand.",
  "/* eslint-disable @typescript-eslint/no-explicit-any -- jsonb columns are typed at the use site */",
  "export interface BaseRow {",
  "  id: string;",
  "  user_id?: string | null;",
  "  created_at: string;",
  "  updated_at: string;",
  "  synced_at?: string | null;",
  "  deleted_at: string | null;",
  "}",
  "",
];
for (const t of TABLE_NAMES) {
  const d = TABLES[t] as TableDef;
  ts.push(`/** ${d.doc} */`, `export interface ${pascal(t)}Row extends BaseRow {`);
  for (const [name, c] of Object.entries(d.cols) as [string, Col][]) {
    const nullable = !c.req && !c.def;
    ts.push(`  ${name}${nullable ? "?" : ""}: ${TST[c.t]}${nullable ? " | null" : ""};`);
  }
  ts.push("}", "");
}
ts.push("export interface Rows {");
for (const t of TABLE_NAMES) ts.push(`  ${t}: ${pascal(t)}Row;`);
ts.push("}", "");
writeFileSync(join(root, "apps", "web", "src", "data", "types.gen.ts"), ts.join("\n"));
